#!/usr/bin/env python3
"""Generate web_ui_gen.c — the UI's assets gzipped into C byte arrays plus
an http_asset_t table. Codegen (rather than EMBED_FILES) so every file in
web/ embeds with correct MIME + gzip, no per-file boilerplate and no
symbol-name collisions. Today web/ holds ONE file (the v2-style single-page
index.html), but the pipeline stays directory-shaped on purpose.

  python gen_assets.py <web_dir> <out.c>
"""
import gzip
import os
import sys

EXCLUDE = {"mock.js"}  # dev-only files, if any reappear
MIME = {
    ".html": "text/html", ".css": "text/css", ".js": "text/javascript",
    ".svg": "image/svg+xml", ".json": "application/json", ".ico": "image/x-icon",
}


def c_array(name, data):
    out = [f"static const uint8_t {name}[] = {{"]
    line = "  "
    for b in data:
        line += f"{b},"
        if len(line) >= 96:
            out.append(line)
            line = "  "
    if line.strip():
        out.append(line)
    out.append("};")
    return "\n".join(out)


def main():
    web_dir, out_c = sys.argv[1], sys.argv[2]
    files = []
    for root, _dirs, names in os.walk(web_dir):
        for n in sorted(names):
            if n in EXCLUDE:
                continue
            full = os.path.join(root, n)
            rel = os.path.relpath(full, web_dir).replace(os.sep, "/")
            files.append((rel, full))
    files.sort()

    blocks, entries = [], []
    for i, (rel, full) in enumerate(files):
        with open(full, "rb") as f:
            gz = gzip.compress(f.read(), 9)
        sym = f"a{i}"
        blocks.append(c_array(sym, gz))
        ext = os.path.splitext(rel)[1]
        ctype = MIME.get(ext, "application/octet-stream")
        entries.append((f"/{rel}", ctype, sym, len(gz)))
        if rel == "index.html":  # also serve at root
            entries.append(("/", ctype, sym, len(gz)))

    with open(out_c, "w", encoding="utf-8") as o:
        o.write("/* GENERATED by gen_assets.py — do not edit. web UI assets. */\n")
        o.write('#include "http_server_manager.h"\n\n')
        o.write("\n\n".join(blocks))
        o.write("\n\nconst http_asset_t web_ui_assets[] = {\n")
        for uri, ctype, sym, n in entries:
            o.write(f'  {{ .uri = "{uri}", .content_type = "{ctype}", '
                    f'.data_start = {sym}, .data_end = {sym} + {n}, '
                    f'.content_encoding = "gzip" }},\n')
        o.write("  { 0 }\n};\n")
    print(f"web_ui: embedded {len(files)} files, {len(entries)} routes")


if __name__ == "__main__":
    main()
